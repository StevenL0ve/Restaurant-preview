import type { CaseCart, MissingEntry, PrefCard, Surgeon } from "../types";

// The digital twin of the paper "Case Pull Verification" sheet: one page per
// cart with the same fields the facility fills in by hand today, populated
// automatically from the cart's pulls, QC marks, and missing-item follow-ups.
// It's a day-of record for handoff, not an archive: the app clears the
// underlying data after the surgical day, so share the PDF if ops wants it.

const MARGIN = 48;

function fmtDate(iso?: string): string {
  if (!iso) return "";
  const d = new Date(iso.length <= 10 ? `${iso}T12:00:00` : iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleDateString();
}

function yesNo(v: boolean): string {
  return v ? "YES" : "NO";
}

export async function cartVerificationBlob(
  card: PrefCard,
  cart: CaseCart,
  surgeon?: Surgeon,
): Promise<Blob> {
  const { jsPDF } = await import("jspdf");
  const autoTable = (await import("jspdf-autotable")).default;

  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const pageW = doc.internal.pageSize.getWidth();
  const usable = pageW - MARGIN * 2;

  const pullers = [...new Set(Object.values(cart.pulls).map((p) => p.by))];
  const open: MissingEntry[] = cart.missing.filter((m) => !m.resolvedAt);
  const resolved: MissingEntry[] = cart.missing.filter((m) => m.resolvedAt);
  const anyMissing = open.length > 0;

  let y = MARGIN + 6;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Case Pull Verification", pageW / 2, y, { align: "center" });
  y += 22;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  const caseLine = [
    card.procedure + (cart.label ? ` (${cart.label})` : ""),
    surgeon?.name,
    `Case day: ${fmtDate(cart.date)}`,
  ].filter(Boolean).join("  ·  ");
  doc.text(caseLine, pageW / 2, y, { align: "center" });
  y += 24;

  const pageH = doc.internal.pageSize.getHeight();
  const ensureRoom = (need: number) => {
    if (y + need > pageH - 60) {
      doc.addPage();
      y = MARGIN;
    }
  };
  const line = (label: string, value: string) => {
    doc.setFontSize(10.5);
    doc.setFont("helvetica", "bold");
    const lw = doc.getTextWidth(label) + 6;
    doc.setFont("helvetica", "normal");
    const wrapped = doc.splitTextToSize(value || " ", usable - lw);
    ensureRoom(wrapped.length * 14 + 10);
    doc.setFont("helvetica", "bold");
    doc.text(label, MARGIN, y);
    doc.setFont("helvetica", "normal");
    doc.text(wrapped, MARGIN + lw, y);
    y += Math.max(1, wrapped.length) * 14 + 4;
  };

  line("OR supplies pulled by:", pullers.join(", ") || "(nobody recorded)");
  line("Any missing supplies:", yesNo(anyMissing));

  if (anyMissing) {
    autoTable(doc, {
      startY: y + 2,
      margin: { left: MARGIN, right: MARGIN },
      head: [["ITEM MISSING", "SUPPLY TRACKING", "SURGEON NOTIFIED", "ORDERED", "ALTERNATE CHOSEN"]],
      body: open.map((m) => [
        `${m.name}${m.detail ? ` (${m.detail})` : ""}${m.qcCheckedAt ? `\nconfirmed at QC by ${m.qcCheckedBy}` : ""}`,
        yesNo(!!m.supplyTracking),
        m.surgeonNotifiedAt ? `YES, ${fmtDate(m.surgeonNotifiedAt)}` : "NO",
        m.orderedAt ? `YES, ${fmtDate(m.orderedAt)}` : "NO",
        m.alternateItem ?? "",
      ]),
      theme: "plain",
      styles: { fontSize: 9, cellPadding: { top: 4, bottom: 4, left: 0, right: 8 }, textColor: [17, 17, 17], lineColor: [200, 200, 200], lineWidth: { bottom: 0.6 } },
      headStyles: { fontStyle: "bold", fontSize: 7.5, textColor: [17, 17, 17], lineColor: [17, 17, 17], lineWidth: { bottom: 1.1 } },
      columnStyles: {
        0: { cellWidth: usable * 0.34 },
        1: { cellWidth: usable * 0.14 },
        2: { cellWidth: usable * 0.17 },
        3: { cellWidth: usable * 0.14 },
        4: { cellWidth: usable * 0.21 },
      },
      rowPageBreak: "avoid",
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
  }

  if (resolved.length) {
    line("Resolved during the day:", resolved.map((m) => `${m.name} (by ${m.resolvedBy})`).join("; "));
  }

  y += 4;
  line(
    "Quality Check performed by:",
    cart.qcDone
      ? `${cart.qcBy}, ${new Date(cart.qcDone).toLocaleString()}`
      : "(not signed off yet)",
  );
  if (cart.qc && Object.keys(cart.qc).length) {
    const qcPeople = [...new Set(Object.values(cart.qc).map((q) => q.by))];
    if (qcPeople.length > 1 || qcPeople[0] !== cart.qcBy) {
      line("Item checks verified by:", qcPeople.join(", "));
    }
  }

  const h = doc.internal.pageSize.getHeight();
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.setTextColor(136, 136, 136);
  doc.text("Generated by ORSync. Day-of record; no patient information.", MARGIN, h - 24);

  return doc.output("blob");
}

export function verificationFilename(procedure: string, date: string): string {
  const slug = procedure.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "cart";
  return `case-pull-verification-${slug}-${date}.pdf`;
}
